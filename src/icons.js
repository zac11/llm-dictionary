/**
 * Render one Lucide-style icon as inline SVG markup.
 * @param {string} name icon key from ICONS
 * @param {string} [className] CSS class (defaults to "icon")
 */
export function icon(name, className = 'icon') {
  const body = ICONS[name];
  if (!body) return '';
  const cls = className ? ` class="${className}"` : '';
  return `<svg${cls} xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}
